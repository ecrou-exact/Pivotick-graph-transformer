#!/usr/bin/env node
// Regenerates packages/misp/src/icons.ts from the vendored misp-iconify
// submodule (packages/misp/vendor/misp-iconify). Pivotick's node renderer
// expects raw SVG markup as a string (baked into buildIconLabelCard's icon
// slot), not a URL, so icons get baked into committed TS source rather
// than referenced as file paths — keeps packages/misp consumable with zero
// build step.
//
// Two kinds of entries:
// - CONCEPT_ICONS: one hand-picked icon per MISP *concept* (Event, Object,
//   ...), from misp-iconify's `simple/` frame, keyed by its bare name.
// - ICON_DIRS: whole misp-iconify folders where every file is one icon for
//   a specific *instance* of a concept (e.g. an Object named "domain-ip",
//   an Attribute typed "ip-dst") — auto-discovered rather than hand-listed
//   since there can be hundreds, and keyed `folder/filename` (not just the
//   bare filename) because instance names collide across folders (e.g.
//   "cookie" is both an attribute type and an object name, with different
//   art) — see import.ts for how a concept's per-instance lookup picks the
//   right prefix.
//
// Re-run after `git submodule update` and after touching either map below,
// then commit the resulting src/icons.ts diff.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const mispDir = path.dirname(path.dirname(fileURLToPath(import.meta.url)))
const svgDir = path.join(mispDir, 'vendor', 'misp-iconify', 'src', 'svg')
const outFile = path.join(mispDir, 'src', 'icons.ts')

// concept name -> path relative to misp-iconify/src/svg
const CONCEPT_ICONS = {
  event: 'simple/event.svg',
  object: 'simple/object.svg',
  attribute: 'simple/attribute.svg',
  galaxy: 'simple/galaxy.svg',
  sighting: 'simple/sighting.svg'
}

// misp-iconify folders where every file is one instance icon, auto-
// discovered rather than hand-listed.
const ICON_DIRS = ['objects', 'attributes', 'galaxies']

function readSvg(relativePath) {
  return readFileSync(path.join(svgDir, relativePath), 'utf8').trim()
}

const entries = Object.entries(CONCEPT_ICONS).map(([name, relativePath]) => [name, readSvg(relativePath)])

for (const dir of ICON_DIRS) {
  const files = readdirSync(path.join(svgDir, dir)).filter(file => file.endsWith('.svg')).sort()
  for (const file of files) {
    const name = `${dir}/${file.slice(0, -'.svg'.length)}`
    entries.push([name, readSvg(path.join(dir, file))])
  }
}

const content = `// Generated by packages/misp/scripts/sync-icons.mjs from the vendored
// misp-iconify submodule — do not edit by hand, re-run the script instead.

export const MISP_ICONS: Record<string, string> = {
${entries.map(([name, svg]) => `  ${JSON.stringify(name)}: ${JSON.stringify(svg)}`).join(',\n')}
}
`

writeFileSync(outFile, content)
console.log(`Wrote ${outFile} with ${entries.length} icon(s)`)
