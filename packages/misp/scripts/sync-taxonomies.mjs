#!/usr/bin/env node
// Maintainer-run script — NOT part of `npm install` or `npm run build`.
//
// Real MISP exports normally already carry the correct colour directly on
// each Tag object (MISP's backend resolves it from the active taxonomy at
// tag-application time), so this is a *fallback*, not the primary source:
// used only when a Tag in the input has no `colour` of its own. Vendored
// the same way as misp-iconify — a pinned git submodule
// (packages/misp/vendor/misp-taxonomies) read at maintain-time, output
// committed, so a plain `npm install` never needs it.
//
// misp-taxonomies (github.com/MISP/misp-taxonomies) is ~190 folders, each
// a `<namespace>/machinetag.json` with two shapes a colour can appear in:
//   - flat: predicates: [{ value, colour?, ... }] — the machine tag is
//     `<namespace>:<predicate.value>` (e.g. `tlp:red`)
//   - nested: predicates: [...], values: [{ predicate, entry: [{ value,
//     colour?, ... }] }] — the machine tag is
//     `<namespace>:<predicate>="<entry.value>"` (e.g.
//     `admiralty-scale:source-reliability="a"`)
// Only entries that actually declare a colour end up in the output map —
// most taxonomy entries don't, and that's fine, it just means no fallback
// exists for them (the Tag's own colour, or no colour, still applies).
//
// Usage: node packages/misp/scripts/sync-taxonomies.mjs
// (requires the submodule checked out: `git submodule update --init`)

import { execFileSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const __dirname = path.dirname(fileURLToPath(import.meta.url))
const pkgDir = path.join(__dirname, '..')
const submoduleDir = path.join(pkgDir, 'vendor', 'misp-taxonomies')
const srcDir = path.join(pkgDir, 'src', 'shared')

const submoduleCommit = execFileSync('git', ['-C', submoduleDir, 'rev-parse', 'HEAD']).toString().trim()

const colors = {}

for (const entry of readdirSync(submoduleDir, { withFileTypes: true })) {
  if (!entry.isDirectory() || entry.name.startsWith('.')) continue
  const machinetagPath = path.join(submoduleDir, entry.name, 'machinetag.json')
  let taxonomy
  try {
    taxonomy = JSON.parse(readFileSync(machinetagPath, 'utf8'))
  } catch {
    continue // not every directory is a taxonomy (e.g. tooling folders)
  }

  const namespace = taxonomy.namespace
  const valuesByPredicate = new Map((taxonomy.values ?? []).map((v) => [v.predicate, v.entry]))

  for (const predicate of taxonomy.predicates ?? []) {
    const entries = valuesByPredicate.get(predicate.value)
    if (entries) {
      for (const entry of entries) {
        if (entry.colour) colors[`${namespace}:${predicate.value}="${entry.value}"`] = entry.colour
      }
    } else if (predicate.colour) {
      colors[`${namespace}:${predicate.value}`] = predicate.colour
    }
  }
}

writeFileSync(
  path.join(srcDir, 'taxonomyColors.generated.ts'),
  `/* eslint-disable */
// AUTO-GENERATED by scripts/sync-taxonomies.mjs from vendor/misp-taxonomies
// (pinned at ${submoduleCommit}) — do not edit by hand. Re-run the script
// (after updating the submodule) to refresh. Double-quoted strings below
// are JSON.stringify output, not a style violation — see eslint-disable.
//
// Machine tag name -> its taxonomy-defined colour, for every taxonomy
// entry that actually declares one (most don't — this is intentionally
// sparse). Used as a fallback only when a Tag in the input has no colour
// of its own — see mispTagColor.ts.

export const MISP_TAXONOMY_COLORS: Readonly<Record<string, string>> = ${JSON.stringify(colors, null, 2)}
`,
)

console.log(`Wrote src/shared/taxonomyColors.generated.ts (${Object.keys(colors).length} coloured entries across ${readdirSync(submoduleDir).length} taxonomy folders)`)
